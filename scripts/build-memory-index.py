#!/usr/bin/env python3
"""Scan memory/**/*.md frontmatter and write memory/INDEX.md (trigger -> file table).

Size cap: entries are added until MAX_BYTES is reached. `pin: true` entries are always
included; the rest are ordered gold > silver > bronze, then by name. Stdlib only.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MEM = ROOT / "memory"
MAX_BYTES = int(sys.argv[1]) if len(sys.argv) > 1 else 4000
TIER_RANK = {"gold": 0, "silver": 1, "bronze": 2}
SKIP = {"SCHEMA.md", "INDEX.md"}


def parse_frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    meta = {}
    for line in m.group(1).splitlines():
        if ":" not in line:
            continue
        key, _, val = line.partition(":")
        val = val.strip()
        if val.startswith("[") and val.endswith("]"):
            meta[key.strip()] = [t.strip() for t in val[1:-1].split(",") if t.strip()]
        else:
            meta[key.strip()] = val
    return meta


def collect():
    entries = []
    for path in sorted(MEM.rglob("*.md")):
        if path.name in SKIP:
            continue
        meta = parse_frontmatter(path.read_text(encoding="utf-8"))
        if "name" not in meta:
            continue
        rel = path.relative_to(MEM)
        tier = rel.parts[0] if rel.parts[0] in TIER_RANK else "bronze"
        entries.append({
            "name": meta["name"],
            "triggers": meta.get("triggers", []),
            "pin": str(meta.get("pin", "")).lower() == "true",
            "tier": tier,
            "rel": rel.as_posix(),
        })
    return entries


def row(e):
    trig = ", ".join(e["triggers"])
    return f"| {trig} | [{e['name']}]({e['rel']}) | {e['tier']} |\n"


def main():
    entries = collect()
    entries.sort(key=lambda e: (not e["pin"], TIER_RANK[e["tier"]], e["name"]))
    header = ("# Memory index\n\n> Generated by scripts/build-memory-index.py. Do not edit by hand.\n\n"
              "| If the prompt mentions... | Load | Tier |\n|---|---|---|\n")
    out, size, dropped = header, len(header.encode()), []
    for e in entries:
        r = row(e)
        if not e["pin"] and size + len(r.encode()) > MAX_BYTES:
            dropped.append(e["name"])
            continue
        out += r
        size += len(r.encode())
    if dropped:
        out += f"\n_{len(dropped)} entries omitted by the {MAX_BYTES}-byte cap: {', '.join(dropped)}_\n"
    (MEM / "INDEX.md").write_text(out, encoding="utf-8")
    print(f"wrote memory/INDEX.md: {len(entries) - len(dropped)} entries, {len(dropped)} dropped")


if __name__ == "__main__":
    main()
